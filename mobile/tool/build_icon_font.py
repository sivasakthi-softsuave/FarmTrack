"""Builds the app's icon font from tool/icons.json (the stroke pictures of the approved UI mockup).

    pip install fonttools shapely svgpathtools
    python tool/build_icon_font.py

Writes assets/fonts/FarmTrackIcons.ttf and lib/core/theme/farmtrack_icons.dart (one `IconData` per picture). The pictures
are 24-unit line drawings (round caps and joins, 2 units wide, like the mockup); each stroke is flattened and widened into
a filled outline, so the font draws exactly what the mockup's SVG draws and `Icon(...)` keeps working everywhere.
Add or change a picture in icons.json, run this script, and commit the three files together.
"""
import json
import math
from pathlib import Path

from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen
from shapely import affinity
from shapely.geometry import LineString, MultiPolygon, Polygon
from shapely.geometry.polygon import orient
from shapely.ops import unary_union
from svgpathtools import parse_path

ROOT = Path(__file__).resolve().parent.parent
EM = 1024
BOX = 24.0  # the pictures are drawn in a 24 x 24 box
FAMILY = "FarmTrackIcons"
FIRST_CODEPOINT = 0xE001
STEP = 0.08  # flattening step, in box units (a 24 px icon: a twelfth of a pixel)
SIMPLIFY = 0.012


def polylines(d: str):
    """The sub-paths of an SVG path as lists of (x, y) points."""
    path = parse_path(d)
    out = []
    for sub in path.continuous_subpaths():
        pts = []
        for seg in sub:
            n = max(2, math.ceil(seg.length() / STEP))
            for i in range(n):
                p = seg.point(i / n)
                pts.append((p.real, p.imag))
        last = sub[-1].point(1.0)
        pts.append((last.real, last.imag))
        out.append(pts)
    return out


def stroke_shape(strokes):
    shapes = []
    for stroke in strokes:
        half = stroke["w"] / 2
        for pts in polylines(stroke["d"]):
            if len(pts) < 2:
                continue
            line = LineString(pts)
            shapes.append(line.buffer(half, quad_segs=16, cap_style="round", join_style="round"))
    return unary_union(shapes).simplify(SIMPLIFY)


def to_glyph(shape):
    # SVG y runs down, font y runs up; the box becomes 0..EM on both axes.
    scale = EM / BOX
    shape = affinity.scale(shape, xfact=scale, yfact=-scale, origin=(0, 0))
    shape = affinity.translate(shape, 0, EM)
    pen = TTGlyphPen(None)
    polys = shape.geoms if isinstance(shape, MultiPolygon) else [shape]
    for poly in polys:
        if not isinstance(poly, Polygon) or poly.is_empty:
            continue
        poly = orient(poly, sign=-1.0)  # TrueType: outer contours clockwise, holes counter-clockwise
        for ring in [poly.exterior, *poly.interiors]:
            pts = [(round(x), round(y)) for x, y in ring.coords[:-1]]
            dedup = [p for i, p in enumerate(pts) if i == 0 or p != pts[i - 1]]
            if len(dedup) < 3:
                continue
            pen.moveTo(dedup[0])
            for p in dedup[1:]:
                pen.lineTo(p)
            pen.closePath()
    return pen.glyph()


def main():
    icons = json.loads((ROOT / "tool" / "icons.json").read_text(encoding="utf-8"))
    names = sorted(icons)
    glyph_names = [".notdef"] + [f"icon_{n}" for n in names]
    codepoints = {FIRST_CODEPOINT + i: f"icon_{n}" for i, n in enumerate(names)}

    glyphs = {".notdef": TTGlyphPen(None).glyph()}
    for n in names:
        glyphs[f"icon_{n}"] = to_glyph(stroke_shape(icons[n]))

    fb = FontBuilder(EM, isTTF=True)
    fb.setupGlyphOrder(glyph_names)
    fb.setupCharacterMap(codepoints)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics({g: (EM, 0) for g in glyph_names})
    # Ascent + descent = one em, so an Icon of size S is exactly S tall and the picture fills it like the SVG box.
    fb.setupHorizontalHeader(ascent=EM, descent=0)
    fb.setupNameTable({"familyName": FAMILY, "styleName": "Regular"})
    fb.setupOS2(
        sTypoAscender=EM, sTypoDescender=0, sTypoLineGap=0, usWinAscent=EM, usWinDescent=0, fsType=0, achVendID="FTRK"
    )
    fb.setupPost()
    out_font = ROOT / "assets" / "fonts" / "FarmTrackIcons.ttf"
    out_font.parent.mkdir(parents=True, exist_ok=True)
    fb.save(str(out_font))

    lines = [
        "// GENERATED by tool/build_icon_font.py from tool/icons.json: do not edit by hand.",
        "import 'package:flutter/widgets.dart';",
        "",
        "/// The line pictures of the approved UI mockup, as an icon font (one picture per meaning).",
        "class FtIcons {",
        "  const FtIcons._();",
        "",
        f"  static const family = '{FAMILY}';",
        "",
    ]
    for i, n in enumerate(names):
        lines.append(f"  static const {n} = IconData(0x{FIRST_CODEPOINT + i:x}, fontFamily: family);")
    lines += ["}", ""]
    out_dart = ROOT / "lib" / "core" / "theme" / "farmtrack_icons.dart"
    out_dart.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(names)} icons -> {out_font.name} ({out_font.stat().st_size // 1024} KB), {out_dart.name}")


if __name__ == "__main__":
    main()
